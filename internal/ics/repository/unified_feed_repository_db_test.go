func TestUnifiedFeedCreateAndGet(t *testing.T) {
	pool := dbtest.Pool(t)
	repo := repository.NewUnifiedFeedRepository(pool)
	ctx := dbtest.Context(t)

	f := seedCalendar(t, pool, "Ada")

	if _, _, err := repo.GetByUserID(ctx, f.owner.ID); err == nil {
		t.Error("a user with no feed returned one")
	}

	feed, err := repo.Create(ctx, f.owner.ID)
	if err != nil {
		t.Fatalf("Create: %v", err)
	}
	// The token is generated by a column default rather than in Go. It is the only thing
	// protecting the feed, so an empty or short one would be a real exposure.
	if len(feed.ICSToken) != 64 {
		t.Errorf("ICSToken is %d characters (%q), want the 64 hex characters of 32 bytes",
			len(feed.ICSToken), feed.ICSToken)
	}
	if feed.UserID != f.owner.ID {
		t.Errorf("UserID = %s, want %s", feed.UserID, f.owner.ID)
	}

	// UNIQUE(user_id): a second feed would give one account two live tokens, only one of
	// which the settings page could ever revoke.
	if _, err := repo.Create(ctx, f.owner.ID); err == nil {
		t.Error("a second unified feed was created for the same user")
	}

	got, calendarIDs, err := repo.GetByUserID(ctx, f.owner.ID)
	if err != nil {
		t.Fatalf("GetByUserID: %v", err)
	}
	if got.ID != feed.ID || got.ICSToken != feed.ICSToken {
		t.Errorf("GetByUserID returned %+v, want the feed just created", got)
	}
	if len(calendarIDs) != 0 {
		t.Errorf("a new feed already includes %d calendars", len(calendarIDs))
	}
}

func TestUnifiedFeedCalendarSelection(t *testing.T) {
	pool := dbtest.Pool(t)
	repo := repository.NewUnifiedFeedRepository(pool)
	ctx := dbtest.Context(t)

	first := seedCalendar(t, pool, "Ada", "Grace")
	second := seedCalendar(t, pool, "Katherine")
	// Both calendars belong to the same owner, which is what the feed requires.
	if _, err := pool.Exec(ctx, `UPDATE calendars SET owner_id = $1 WHERE id = $2`,
		first.owner.ID, second.calendar.ID); err != nil {
		t.Fatalf("reassign the second calendar: %v", err)
	}

	feed, err := repo.Create(ctx, first.owner.ID)
	if err != nil {
		t.Fatalf("Create: %v", err)
	}

	if err := repo.UpdateCalendars(ctx, feed.ID, []uuid.UUID{first.calendar.ID, second.calendar.ID}); err != nil {
		t.Fatalf("UpdateCalendars: %v", err)
	}

	_, included, err := repo.GetByUserID(ctx, first.owner.ID)
	if err != nil {
		t.Fatalf("GetByUserID: %v", err)
	}
	if len(included) != 2 {
		t.Fatalf("the feed includes %d calendars, want 2", len(included))
	}

	// UpdateCalendars replaces rather than adds: unticking a calendar in the settings
	// page has to actually remove it from the feed, or a revoked calendar keeps exporting.
	if err := repo.UpdateCalendars(ctx, feed.ID, []uuid.UUID{second.calendar.ID}); err != nil {
		t.Fatalf("UpdateCalendars: %v", err)
	}
	_, included, err = repo.GetByUserID(ctx, first.owner.ID)
	if err != nil {
		t.Fatalf("GetByUserID: %v", err)
	}
	if len(included) != 1 || included[0] != second.calendar.ID {
		t.Errorf("the feed includes %v, want only the second calendar", included)
	}

	// An empty selection clears the feed entirely; the transaction still has to commit.
	if err := repo.UpdateCalendars(ctx, feed.ID, nil); err != nil {
		t.Fatalf("UpdateCalendars with nothing selected: %v", err)
	}
	_, included, err = repo.GetByUserID(ctx, first.owner.ID)
	if err != nil {
		t.Fatalf("GetByUserID: %v", err)
	}
	if len(included) != 0 {
		t.Errorf("the feed still includes %v after being cleared", included)
	}
}

