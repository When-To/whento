// Skips when DATABASE_URL is unset; see internal/testutil/dbtest.
//
// An ICS token is a bearer credential: whoever holds the URL reads the feed, for ever,
// with no other check. Everything below is about what that token resolves to — which
// calendars, whose name — and about the two operations that bound the exposure:
// regenerating the token and validating that a user may add a calendar at all.

func TestGetCalendarByICSToken(t *testing.T) {
	pool := dbtest.Pool(t)
	repo := repository.NewCalendarRepository(pool)
	ctx := dbtest.Context(t)

	f := seedCalendar(t, pool, "Ada", "Grace", "Katherine")

	cal, err := repo.GetByICSToken(ctx, f.calendar.ICSToken)
	if err != nil {
		t.Fatalf("GetByICSToken: %v", err)
	}

	if cal.ID != f.calendar.ID || cal.Name != "ICS Test" {
		t.Errorf("got %+v, want the seeded calendar", cal)
	}
	if cal.Description != "A calendar to export" {
		t.Errorf("Description = %q", cal.Description)
	}
	if cal.OwnerID != f.owner.ID {
		t.Errorf("OwnerID = %s, want %s", cal.OwnerID, f.owner.ID)
	}
	// The participant count comes from a LEFT JOIN with a GROUP BY. It feeds the
	// "2/3 available" line, so a miscount is visible in every exported event.
	if cal.TotalParticipants != 3 {
		t.Errorf("TotalParticipants = %d, want 3", cal.TotalParticipants)
	}
	if cal.Threshold != 2 || cal.MinDurationHours != 1 || cal.Timezone != "Europe/Paris" {
		t.Errorf("the calendar rules did not survive the scan: %+v", cal)
	}

	if _, err := repo.GetByICSToken(ctx, "no-such-token"); err == nil {
		t.Error("an unknown ICS token returned a calendar")
	}
}

