/*
 * Generates `src/types/api.generated.ts` from the backend's OpenAPI description.
 *
 * The backend annotations are compiled by `make swagger` (swaggo) into
 * `docs/swagger/swagger.json`, which is **Swagger 2.0**. `openapi-typescript`
 * only reads OpenAPI 3.x, so the document is converted in memory with
 * `swagger2openapi` first; nothing on disk is touched but the output file.
 *
 * `docs/swagger/` is git-ignored and regenerated from the Go sources, whereas
 * the TypeScript output *is* committed on purpose: that is what makes a backend
 * API break show up as a reviewable diff in the pull request that causes it.
 *
 * Usage: npm run generate:api-types   (or `make types` from the repository root)
 */

import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
// Imported rather than taken from the global scope: this file is outside the
// ESLint config's Node-globals block, and the explicit import keeps it linted as
// strictly as the rest of the tree.
import process from 'node:process';
import { fileURLToPath } from 'node:url';

import openapiTS, { astToString } from 'openapi-typescript';
import converter from 'swagger2openapi';

const here = dirname(fileURLToPath(import.meta.url));
const frontendRoot = resolve(here, '..');
const specPath = resolve(frontendRoot, '../docs/swagger/swagger.json');
const outputPath = resolve(frontendRoot, 'src/types/api.generated.ts');

const banner = `/*
 * WhenTo - Collaborative event calendar for self-hosted environments
 * Copyright (C) 2025 WhenTo Contributors
 * SPDX-License-Identifier: BSL-1.1
 */

/*
 * GENERATED FILE - DO NOT EDIT.
 *
 * Produced by \`npm run generate:api-types\` (\`make types\`) from
 * docs/swagger/swagger.json, itself generated by \`make swagger\` from the
 * // @... annotations in the Go handlers.
 *
 * To change anything here, change the Go annotation and regenerate both.
 *
 * Note on optionality: swaggo only marks a property \`required\` when the Go
 * struct carries a \`validate:"required"\` tag, which response models do not. So
 * every response field below is optional even though the backend always sends
 * it. src/types/index.ts is where that knowledge is applied, by re-deriving the
 * application types from these schemas.
 */

`;

function fail(message) {
  process.stderr.write(`generate-api-types: ${message}\n`);
  process.exit(1);
}

let swagger;
try {
  swagger = JSON.parse(readFileSync(specPath, 'utf8'));
} catch (error) {
  if (error.code === 'ENOENT') {
    fail(
      `${specPath} not found.\n` +
        'docs/swagger/ is git-ignored and generated from the Go annotations: ' +
        'run `make swagger` at the repository root first.'
    );
  }
  fail(`could not read ${specPath}: ${error.message}`);
}

if (swagger.swagger !== '2.0' && !swagger.openapi) {
  fail('the specification is neither Swagger 2.0 nor OpenAPI 3.x.');
}

// swaggo emits Swagger 2.0; convert in memory. `patch` repairs the small
// inconsistencies swaggo leaves behind (missing descriptions, empty responses)
// rather than aborting the conversion over them.
const openapi = swagger.openapi
  ? swagger
  : (await converter.convertObj(swagger, { patch: true, warnOnly: true })).openapi;

const ast = await openapiTS(openapi, {
  alphabetize: true,
  // The `enums` option would emit real TS enums; string unions inline are
  // lighter and match how the rest of the codebase models closed sets.
  enum: false,
});

writeFileSync(outputPath, banner + astToString(ast), 'utf8');

// Formatted with the repository's own Prettier settings so that `npm run
// format:check` stays green without anyone having to remember to run it.
const prettier = spawnSync('npx', ['prettier', '--write', outputPath], {
  cwd: frontendRoot,
  stdio: 'inherit',
});
if (prettier.status !== 0) {
  fail('prettier failed on the generated file.');
}

process.stdout.write(`generate-api-types: wrote ${outputPath}\n`);
